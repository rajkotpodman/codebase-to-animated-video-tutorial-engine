# Provider 3: Coqui XTTS Provider (Local Zero-Shot Voice Cloning)
# -----------------------------------------------------------------------------


class CoquiXTTSProvider(BaseTTSProvider):
    """Integrates local Coqui XTTS v2 server endpoints."""

    def __init__(self, api_url: Optional[str] = None) -> None:
        self.api_url = api_url or "http://localhost:8020/tts_to_audio/"

    async def synthesize(
        self,
        scene_segments: List[Dict[str, Any]],
        options: TTSOptions,
        output_audio_path: Path,
    ) -> Tuple[List[SubtitleCue], float]:
        try:
            import httpx
        except ImportError as exc:
            raise RuntimeError("httpx is required for Coqui XTTS client. Run 'pip install httpx'.") from exc

        full_text = " ".join(
            ScriptCleaner.clean_narration_text(s["text"], language=options.language) for s in scene_segments
        )
        payload = {
            "text": full_text,
            "speaker_wav": "female_clean.wav",
            "language": options.language,
        }

        try:
            async with httpx.AsyncClient(timeout=90.0) as client:
                resp = await client.post(self.api_url, json=payload)
                if resp.status_code != 200:
                    raise RuntimeError(f"Coqui XTTS server error {resp.status_code}: {resp.text}")
                audio_bytes = resp.content
        except Exception as err:
            logger.warning("Local Coqui XTTS server unavailable (%s), falling back to EdgeTTSProvider", err)
            fallback = EdgeTTSProvider()
            return await fallback.synthesize(scene_segments, options, output_audio_path)

        output_audio_path.parent.mkdir(parents=True, exist_ok=True)
        output_audio_path.write_bytes(audio_bytes)

        # Estimate duration (~14 chars/sec average human speech)
        duration = max(2.0, len(full_text) / 14.5)
        cue = SubtitleCue(index=1, start_time=0.0, end_time=duration, text=full_text)
        return [cue], duration


