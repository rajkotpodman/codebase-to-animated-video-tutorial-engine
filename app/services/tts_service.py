# Timestamp & SRT Helpers
# -----------------------------------------------------------------------------


def format_srt_timestamp(seconds: float) -> str:
    """Convert floating point seconds into standard SRT timecode (HH:MM:SS,mmm)."""
    total_ms = max(0, int(round(seconds * 1000)))
    hours = total_ms // 3_600_000
    total_ms %= 3_600_000
    minutes = total_ms // 60_000
    total_ms %= 60_000
    secs = total_ms // 1000
    millis = total_ms % 1000
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{millis:03d}"


@dataclasses.dataclass
class SubtitleCue:
    """Individual subtitle block with timing and text for video overlay."""

    index: int
    start_time: float  # In seconds
    end_time: float  # In seconds
    text: str
    scene_id: Optional[str] = None

    @property
    def start_srt(self) -> str:
        return format_srt_timestamp(self.start_time)

    @property
    def end_srt(self) -> str:
        return format_srt_timestamp(self.end_time)

    @property
    def duration(self) -> float:
        return max(0.0, self.end_time - self.start_time)

    def to_srt_block(self) -> str:
        """Format as a single standard SRT cue entry."""
        return f"{self.index}\n{self.start_srt} --> {self.end_srt}\n{self.text.strip()}\n"


# -----------------------------------------------------------------------------
# Script Cleaner & Preprocessor (Gemini Technical Script Normalizer)
# -----------------------------------------------------------------------------


class ScriptCleaner:
    """Normalizes technical scripts generated by LLMs like Gemini for natural TTS playback."""

    # Matches scene markers like [Scene 1: Architecture Overview]
    SCENE_HEADER_REGEX = re.compile(r"^\s*\[(?:Scene|Act)\s*([0-9a-zA-Z_\-:\s]+)\]\s*$", re.IGNORECASE)
    DIRECTOR_NOTE_REGEX = re.compile(r"\[(?:Visual|Action|Camera|Note|Cut to|Music|Pause|Wait)[^\]]*\]", re.IGNORECASE)

    # Phonetic pronunciation normalizers for code terminology
    PRONUNCIATION_REPLACEMENTS = [
        (re.compile(r"\bFastAPI\b"), "Fast A P I"),
        (re.compile(r"\bPostgreSQL\b"), "Postgres Q L"),
        (re.compile(r"\bPostgres\b"), "Postgres"),
        (re.compile(r"\bgRPC\b"), "g R P C"),
        (re.compile(r"\b__init__\.py\b"), "dunder init dot py"),
        (re.compile(r"\b__init__\b"), "dunder init"),
        (re.compile(r"\b\.__([a-zA-Z0-9_]+)__\b"), r" dunder \1 dunder "),
        (re.compile(r"\bSQL\b"), "S Q L"),
        (re.compile(r"\bJSON\b"), "Jason"),
        (re.compile(r"\bAPI\b"), "A P I"),
        (re.compile(r"\bAPIs\b"), "A P I's"),
        (re.compile(r"\bCLI\b"), "C L I"),
        (re.compile(r"\bTTS\b"), "T T S"),
        (re.compile(r"\bUUID\b"), "U U I D"),
        (re.compile(r"\bSHA\b"), "shah"),
        (re.compile(r"\bOAuth\b"), "O Auth"),
        (re.compile(r"\bJWT\b"), "J W T"),
        (re.compile(r"\bCRUD\b"), "Crud"),
        (re.compile(r"\bAST\b"), "A S T"),
        (re.compile(r"\bGUI\b"), "gooey"),
        (re.compile(r"\bv([0-9]+)\.([0-9]+)\b"), r"version \1 point \2"),
        (re.compile(r"`([^`]+)`"), r"\1"),  # Strip inline code backticks
        (re.compile(r"`"), ""),  # Strip any stray backticks
        (re.compile(r"\*\*([^\*]+)\*\*"), r"\1"),  # Strip bold
        (re.compile(r"\*([^\*]+)\*"), r"\1"),  # Strip italics
    ]

    @classmethod
    def parse_script_scenes(cls, script_text: str, language: str = "en") -> List[Dict[str, Any]]:
        """Split script into scene-tagged segments, stripping visual cues."""
        lines = script_text.splitlines()
        segments: List[Dict[str, Any]] = []
        current_scene: Optional[str] = None
        current_lines: List[str] = []

        for line in lines:
            trimmed = line.strip()
            if not trimmed:
                continue

            # Ignore top-level document headers before the first scene tag
            if current_scene is None and trimmed.startswith("#"):
                continue

            # Check for scene heading: [Scene 1: Introduction]
            scene_match = cls.SCENE_HEADER_REGEX.match(trimmed)
            if scene_match:
                if current_lines and current_scene is not None:
                    raw_content = " ".join(current_lines).strip()
                    cleaned_content = cls.clean_narration_text(raw_content, language=language)
                    if cleaned_content:
                        segments.append({"scene_id": current_scene, "text": cleaned_content})
                    current_lines = []
                current_scene = scene_match.group(1).strip().replace(" ", "_").lower()
                continue

            # Strip inline visual director notes and pause cues
            cleaned_line = cls.DIRECTOR_NOTE_REGEX.sub("", trimmed)

            # Convert markdown headings "# Heading" to spoken text
            cleaned_line = re.sub(r"^#+\s*", "", cleaned_line)

            if cleaned_line.strip():
                current_lines.append(cleaned_line.strip())

        if current_lines:
            target_scene = current_scene or "main"
            raw_content = " ".join(current_lines).strip()
            cleaned_content = cls.clean_narration_text(raw_content, language=language)
            if cleaned_content:
                segments.append({"scene_id": target_scene, "text": cleaned_content})

        if not segments:
            # Fallback if no scene markers
            clean_full = cls.clean_narration_text(script_text, language=language)
            segments.append({"scene_id": "main", "text": clean_full})

        return segments

    @classmethod
    def clean_narration_text(cls, text: str, language: str = "en") -> str:
        """Sanitize text for clean and natural TTS pronunciation."""
        s = cls.DIRECTOR_NOTE_REGEX.sub("", text)
        s = cls.SCENE_HEADER_REGEX.sub("", s)
        s = re.sub(r"^#+\s*", "", s, flags=re.MULTILINE)

        # Apply phonetic expansions
        for pattern, replacement in cls.PRONUNCIATION_REPLACEMENTS:
            s = pattern.sub(replacement, s)

        # Apply text normalization to remove code artifacts and format technical identifiers
        s = normalize_text_for_tts(s, language=language)

        # Normalize whitespace and ellipsis
        s = re.sub(r"\.{3,}", " ... ", s)
        s = re.sub(r"\s+", " ", s).strip()
        return s


