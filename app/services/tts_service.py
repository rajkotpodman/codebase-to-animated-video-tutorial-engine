# Provider 2: ElevenLabs TTS Client (Studio Voice Cloning & Timestamps)
# -----------------------------------------------------------------------------


class ElevenLabsTTSProvider(BaseTTSProvider):
    """API-based TTS provider using ElevenLabs with timestamp alignment."""

    def __init__(self, api_key: Optional[str] = None) -> None:
        self.api_key = api_key or os.environ.get("ELEVENLABS_API_KEY")

    async def synthesize(
        self,
        scene_segments: List[Dict[str, Any]],
        options: TTSOptions,
        output_audio_path: Path,
    ) -> Tuple[List[SubtitleCue], float]:
        if not self.api_key:
            raise ValueError(
                "ElevenLabs API key is missing. Set ELEVENLABS_API_KEY environment variable "
                "or pass it in TTSOptions(elevenlabs_api_key='...')."
            )

        try:
            import httpx
        except ImportError as exc:
            raise RuntimeError("httpx is required for ElevenLabs API client. Run 'pip install httpx'.") from exc

        voice_id = options.elevenlabs_voice_id or "21m00Tcm4TlvDq8ikWAM"
        endpoint = f"https://api.elevenlabs.io/v1/text-to-speech/{voice_id}/with-timestamps"

        headers = {
            "xi-api-key": self.api_key,
            "Content-Type": "application/json",
            "Accept": "application/json",
        }

        full_text_parts = []
        for seg in scene_segments:
            cleaned = ScriptCleaner.clean_narration_text(seg["text"], language=options.language)
            if cleaned:
                full_text_parts.append(cleaned)

        full_text = " ".join(full_text_parts)

        payload = {
            "text": full_text,
            "model_id": "eleven_multilingual_v2",
            "voice_settings": {
                "stability": 0.5,
                "similarity_boost": 0.75,
            },
        }

        logger.info("Calling ElevenLabs API endpoint: %s", endpoint)
        async with httpx.AsyncClient(timeout=60.0) as client:
            resp = await client.post(endpoint, json=payload, headers=headers)
            if resp.status_code != 200:
                raise RuntimeError(f"ElevenLabs API returned {resp.status_code}: {resp.text}")
            data = resp.json()

        # Extract audio and alignment
        audio_b64 = data.get("audio_base64", "")
        audio_bytes = base64.b64decode(audio_b64)
        output_audio_path.parent.mkdir(parents=True, exist_ok=True)
        output_audio_path.write_bytes(audio_bytes)

        # Parse character alignment timestamps into subtitle cues
        alignment = data.get("alignment", {})
        subtitles, duration = self._parse_alignment(alignment, full_text, options.max_chars_per_subtitle)
        return subtitles, duration

    @staticmethod
    def _parse_alignment(
        alignment: Dict[str, Any],
        text: str,
        max_chars: int = 80,
    ) -> Tuple[List[SubtitleCue], float]:
        """Convert ElevenLabs character start/end times into subtitle cues."""
        chars = alignment.get("characters", [])
        char_starts = alignment.get("character_start_times_seconds", [])
        char_ends = alignment.get("character_end_times_seconds", [])

        if not chars or not char_starts:
            # Fallback estimation if alignment is omitted
            dur = max(2.0, len(text) / 14.0)
            return [SubtitleCue(index=1, start_time=0.0, end_time=dur, text=text)], dur

        total_duration = max(char_ends) if char_ends else len(text) / 14.0

        # Group words based on spaces and punctuation
        words_timing: List[Tuple[str, float, float]] = []
        cur_word: List[str] = []
        word_start: Optional[float] = None
        word_end: Optional[float] = None

        for c, s, e in zip(chars, char_starts, char_ends):
            if c.isspace():
                if cur_word and word_start is not None and word_end is not None:
                    words_timing.append(("".join(cur_word), word_start, word_end))
                    cur_word = []
                    word_start = None
                    word_end = None
            else:
                if word_start is None:
                    word_start = s
                word_end = e
                cur_word.append(c)

        if cur_word and word_start is not None and word_end is not None:
            words_timing.append(("".join(cur_word), word_start, word_end))

        # Group words into subtitle lines (approx 60-80 chars)
        subtitles: List[SubtitleCue] = []
        cur_line_words: List[str] = []
        cur_line_start: Optional[float] = None
        cur_line_end: Optional[float] = None
        cue_idx = 1

        for w, w_start, w_end in words_timing:
            if cur_line_start is None:
                cur_line_start = w_start
            cur_line_end = w_end
            cur_line_words.append(w)

            current_len = sum(len(x) + 1 for x in cur_line_words)
            if current_len >= max_chars or w.endswith((".", "!", "?")):
                cue = SubtitleCue(
                    index=cue_idx,
                    start_time=round(cur_line_start, 3),
                    end_time=round(cur_line_end, 3),
                    text=" ".join(cur_line_words),
                )
                subtitles.append(cue)
                cue_idx += 1
                cur_line_words = []
                cur_line_start = None

        if cur_line_words and cur_line_start is not None and cur_line_end is not None:
            cue = SubtitleCue(
                index=cue_idx,
                start_time=round(cur_line_start, 3),
                end_time=round(cur_line_end, 3),
                text=" ".join(cur_line_words),
            )
            subtitles.append(cue)

        return subtitles, total_duration


