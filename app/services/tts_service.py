"""Text-to-Speech (TTS) & Subtitle Synchronization Service.

Takes technical scripts generated by AI (e.g. Gemini API), converts them into human-like
voiceover audio files (.mp3/.wav), and simultaneously generates millisecond-accurate timestamped
.srt subtitle files and scene timing markers for video synchronization.

Supports:
  1. EdgeTTSProvider: High-quality Microsoft Neural TTS (free, zero-config, open-source).
  2. ElevenLabsTTSProvider: Studio voice cloning & API-based TTS with character timestamps.
  3. CoquiXTTSProvider: Open-source local XTTS v2 server integration.
"""

