@dataclasses.dataclass(frozen=True)
class TTSOptions:
    """Configuration options for speech synthesis and subtitle timing."""

    provider: Literal["auto", "edge", "elevenlabs", "coqui"] = "auto"
    voice: str = "en-US-ChristopherNeural"
    output_format: Literal["mp3", "wav"] = "mp3"
    rate: str = "+0%"  # e.g. "+5%", "-10%"
    pitch: str = "+0Hz"  # e.g. "+5Hz", "-5Hz"
    volume: str = "+0%"
    language: str = "en"
    elevenlabs_api_key: Optional[str] = None
    elevenlabs_voice_id: Optional[str] = "21m00Tcm4TlvDq8ikWAM"  # Default 'Rachel'
    coqui_api_url: Optional[str] = "http://localhost:8020/tts_to_audio/"
    max_chars_per_subtitle: int = 80


@dataclasses.dataclass
class TTSResult:
    """Output artifact container containing voiceover audio and synchronized subtitles."""

    audio_path: Path
    srt_path: Path
    duration_seconds: float
    subtitles: List[SubtitleCue]
    srt_content: str
    voice_used: str
    provider_used: str
    audio_format: str
    file_size_bytes: int
    scene_timestamps: Dict[str, float] = dataclasses.field(default_factory=dict)

    def find_cue_at_timestamp(self, seconds: float) -> Optional[SubtitleCue]:
        """Find the active subtitle cue for a given playback timestamp."""
        for cue in self.subtitles:
            if cue.start_time <= seconds <= cue.end_time:
                return cue
        return None

    def get_scene_start_time(self, scene_id: str) -> Optional[float]:
        """Retrieve start timestamp for an architectural scene tag."""
        return self.scene_timestamps.get(scene_id)

    def save_to(self, audio_dest: Path | str, srt_dest: Optional[Path | str] = None) -> Tuple[Path, Path]:
        """Copy generated audio and subtitle files to specific output locations."""
        a_dest = Path(audio_dest).resolve()
        a_dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(self.audio_path, a_dest)

        if srt_dest:
            s_dest = Path(srt_dest).resolve()
        else:
            s_dest = a_dest.with_suffix(".srt")

        s_dest.parent.mkdir(parents=True, exist_ok=True)
        s_dest.write_text(self.srt_content, encoding="utf-8")
        return a_dest, s_dest


# -----------------------------------------------------------------------------
# Base TTS Provider Interface
