# Primary TTS & Video Synchronization Service
# -----------------------------------------------------------------------------


class TTSService:
    """Production service for generating technical narration audio and video subtitles."""

    def __init__(self, workspace_dir: Optional[Path | str] = None) -> None:
        self.workspace_dir = Path(workspace_dir).resolve() if workspace_dir else None
        if self.workspace_dir:
            self.workspace_dir.mkdir(parents=True, exist_ok=True)

    def synthesize_script(
        self,
        script_text: str,
        output_dir: Optional[Path | str] = None,
        options: Optional[TTSOptions] = None,
    ) -> TTSResult:
        """Synchronously convert a technical script into voiceover audio and .srt subtitles."""
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            loop = None

        if loop and loop.is_running():
            import nest_asyncio

            nest_asyncio.apply()
            return loop.run_until_complete(self.async_synthesize_script(script_text, output_dir, options))
        return asyncio.run(self.async_synthesize_script(script_text, output_dir, options))

    async def async_synthesize_script(
        self,
        script_text: str,
        output_dir: Optional[Path | str] = None,
        options: Optional[TTSOptions] = None,
    ) -> TTSResult:
        """Asynchronously convert a technical script into voiceover audio and .srt subtitles.

        Args:
            script_text: Raw technical script (e.g. from Gemini API with scene markers).
            output_dir: Destination folder for output files (.mp3, .wav, .srt).
            options: Configuration options (voice, speed, format, provider).

        Returns:
            TTSResult containing file paths, SRT string, timing cues, and duration.
        """
        opts = options or TTSOptions()
        # Automatically resolve native neural voice if language is non-English and voice is default or empty
        if opts.language and opts.language != "en" and (opts.voice == "en-US-ChristopherNeural" or not opts.voice):
            lang_info = resolve_language_info(opts.language)
            opts = dataclasses.replace(opts, voice=lang_info.default_voice)
            logger.info("Auto-resolved native voice '%s' for language '%s'", opts.voice, opts.language)

        target_dir = (
            Path(output_dir).resolve()
            if output_dir
            else (self.workspace_dir or Path(tempfile.mkdtemp(prefix="tts_output_")))
        )
        target_dir.mkdir(parents=True, exist_ok=True)

        timestamp_slug = int(time.time() * 1000)
        base_name = f"voiceover_{timestamp_slug}"
        mp3_path = target_dir / f"{base_name}.mp3"
        srt_path = target_dir / f"{base_name}.srt"

        # 1. Parse script into scene segments using target language normalization
        scene_segments = ScriptCleaner.parse_script_scenes(script_text, language=opts.language)

        # 2. Select TTS provider
        provider = self._resolve_provider(opts)

        # 3. Synthesize voiceover audio
        start_clock = time.perf_counter()
        logger.info("Starting speech synthesis via %s (voice=%s)", provider.__class__.__name__, opts.voice)
        subtitles, duration = await provider.synthesize(scene_segments, opts, mp3_path)
        logger.info("TTS completed in %.2fs (audio duration: %.2fs)", time.perf_counter() - start_clock, duration)

        # 4. Generate timestamped .srt content
        srt_content = "\n".join(cue.to_srt_block() for cue in subtitles)
        srt_path.write_text(srt_content, encoding="utf-8")

        # 5. Extract scene starting timestamps for animation synchronization
        scene_timestamps: Dict[str, float] = {}
        for cue in subtitles:
            if cue.scene_id and cue.scene_id not in scene_timestamps:
                scene_timestamps[cue.scene_id] = cue.start_time

        # 6. Audio format conversion (MP3 -> WAV) if requested
        final_audio_path = mp3_path
        if opts.output_format == "wav":
            wav_path = target_dir / f"{base_name}.wav"
            self._convert_to_wav(mp3_path, wav_path)
            final_audio_path = wav_path

        file_size = final_audio_path.stat().st_size if final_audio_path.exists() else 0

        return TTSResult(
            audio_path=final_audio_path,
            srt_path=srt_path,
            duration_seconds=duration,
            subtitles=subtitles,
            srt_content=srt_content,
            voice_used=opts.voice,
            provider_used=provider.__class__.__name__,
            audio_format=opts.output_format,
            file_size_bytes=file_size,
            scene_timestamps=scene_timestamps,
        )

    # -------------------------------------------------------------------------
    # Internal Helpers
    # -------------------------------------------------------------------------

    def _resolve_provider(self, options: TTSOptions) -> BaseTTSProvider:
        """Resolve TTS provider instance based on options and availability."""
        if options.provider == "elevenlabs" or (options.provider == "auto" and options.elevenlabs_api_key):
            try:
                return ElevenLabsTTSProvider(api_key=options.elevenlabs_api_key)
            except Exception as err:
                logger.warning("ElevenLabs provider failed to initialize: %s. Using EdgeTTSProvider.", err)

        if options.provider == "coqui":
            return CoquiXTTSProvider(api_url=options.coqui_api_url)

        # Default high-quality open-source neural TTS
        return EdgeTTSProvider()

    @staticmethod
    def _convert_to_wav(source_mp3: Path, target_wav: Path) -> None:
        """Convert MP3 to uncompressed 16-bit PCM WAV using FFmpeg."""
        ffmpeg_bin = shutil.which("ffmpeg")
        if not ffmpeg_bin:
            try:
                import imageio_ffmpeg

                ffmpeg_bin = imageio_ffmpeg.get_ffmpeg_exe()
            except Exception as exc:
                logger.debug("imageio-ffmpeg resolution fallback: %s", exc)

        if not ffmpeg_bin:
            logger.warning("FFmpeg binary not found; keeping original MP3 format for %s", target_wav)
            return

        cmd = [
            ffmpeg_bin,
            "-y",
            "-i",
            str(source_mp3),
            "-acodec",
            "pcm_s16le",
            "-ar",
            "44100",
            "-ac",
            "2",
            str(target_wav),
        ]
        subprocess.run(cmd, capture_output=True, check=False)
