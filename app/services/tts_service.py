class BaseTTSProvider(ABC):
    """Abstract contract for text-to-speech engines."""

    @abstractmethod
    async def synthesize(
        self,
        scene_segments: List[Dict[str, Any]],
        options: TTSOptions,
        output_audio_path: Path,
    ) -> Tuple[List[SubtitleCue], float]:
        """Synthesize text segments into audio and return (subtitles, total_duration)."""
        pass


# -----------------------------------------------------------------------------
# Provider 1: EdgeTTS (Free, Zero-Config Neural Voices)
# -----------------------------------------------------------------------------


class EdgeTTSProvider(BaseTTSProvider):
    """Open-source Microsoft Neural TTS provider using edge-tts.

    Captures exact sentence and word boundaries for accurate video subtitle alignment.
    """

    async def synthesize(
        self,
        scene_segments: List[Dict[str, Any]],
        options: TTSOptions,
        output_audio_path: Path,
    ) -> Tuple[List[SubtitleCue], float]:
        try:
            import edge_tts
        except ImportError as exc:
            raise RuntimeError("edge-tts is not installed. Run 'pip install edge-tts'.") from exc

        subtitles: List[SubtitleCue] = []
        global_cue_index = 1
        time_offset_seconds = 0.0

        # Create output directory
        output_audio_path.parent.mkdir(parents=True, exist_ok=True)
        if output_audio_path.exists():
            output_audio_path.unlink()

        # Temporary file for raw mp3 stream
        temp_mp3 = output_audio_path.with_suffix(".temp.mp3")

        with temp_mp3.open("wb") as master_audio:
            for segment in scene_segments:
                scene_id = segment["scene_id"]
                raw_text = segment["text"]
                cleaned_text = ScriptCleaner.clean_narration_text(raw_text, language=options.language)

                if not cleaned_text:
                    continue

                comm = edge_tts.Communicate(
                    text=cleaned_text,
                    voice=options.voice,
                    rate=options.rate,
                    pitch=options.pitch,
                    volume=options.volume,
                )

                segment_max_end = 0.0

                async for chunk in comm.stream():
                    if chunk["type"] == "audio":
                        master_audio.write(chunk["data"])
                    elif chunk["type"] == "SentenceBoundary":
                        # Convert 100-nanosecond ticks to seconds
                        start_s = time_offset_seconds + (chunk["offset"] / 10_000_000)
                        duration_s = chunk["duration"] / 10_000_000
                        end_s = start_s + duration_s
                        segment_max_end = max(segment_max_end, (chunk["offset"] + chunk["duration"]) / 10_000_000)

                        sentence_text = chunk["text"].strip()
                        if sentence_text:
                            # Split very long sentences into readable subtitle chunks if necessary
                            chunks = self._split_long_sentence(
                                sentence_text, start_s, end_s, options.max_chars_per_subtitle
                            )
                            for c_start, c_end, c_text in chunks:
                                cue = SubtitleCue(
                                    index=global_cue_index,
                                    start_time=c_start,
                                    end_time=c_end,
                                    text=c_text,
                                    scene_id=scene_id,
                                )
                                subtitles.append(cue)
                                global_cue_index += 1

                # Advance offset by segment duration
                time_offset_seconds += segment_max_end

        # Calculate exact audio duration using probe or file metadata
        duration = time_offset_seconds
        if subtitles:
            duration = max(duration, subtitles[-1].end_time + 0.2)

        # Move temp to final output
        if temp_mp3.exists():
            if output_audio_path.exists():
                output_audio_path.unlink()
            temp_mp3.rename(output_audio_path)

        return subtitles, duration

    @staticmethod
    def _split_long_sentence(
        text: str,
        start_time: float,
        end_time: float,
        max_chars: int = 80,
    ) -> List[Tuple[float, float, str]]:
        """Split long sentences across multiple subtitle cues with proportional durations."""
        if len(text) <= max_chars:
            return [(start_time, end_time, text)]

        words = text.split()
        if len(words) <= 1:
            return [(start_time, end_time, text)]

        lines: List[str] = []
        cur_line: List[str] = []
        cur_len = 0

        for w in words:
            if cur_len + len(w) + 1 > max_chars and cur_line:
                lines.append(" ".join(cur_line))
                cur_line = [w]
                cur_len = len(w)
            else:
                cur_line.append(w)
                cur_len += len(w) + 1

        if cur_line:
            lines.append(" ".join(cur_line))

        total_chars = sum(len(ln) for ln in lines)
        total_duration = max(0.2, end_time - start_time)

        results: List[Tuple[float, float, str]] = []
        cur_start = start_time

        for i, ln in enumerate(lines):
            line_weight = len(ln) / total_chars if total_chars > 0 else 1.0 / len(lines)
            line_dur = total_duration * line_weight
            line_end = cur_start + line_dur
            if i == len(lines) - 1:
                line_end = end_time  # Match exact end
            results.append((round(cur_start, 3), round(line_end, 3), ln))
            cur_start = line_end

        return results


