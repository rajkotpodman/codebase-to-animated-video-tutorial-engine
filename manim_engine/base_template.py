# Layered Layout Engine
# -----------------------------------------------------------------------------


class LayeredLayoutEngine:
    """Computes coordinate positions for nodes arranged in hierarchical tiers."""

    @classmethod
    def compute_positions(cls, nodes: List[NodeModel]) -> Dict[str, Tuple[float, float, float]]:
        """Calculate balanced [x, y, z] Manim coordinates for each node."""
        layers: Dict[int, List[NodeModel]] = {}
        for node in nodes:
            layer_idx = node.layer if node.layer is not None else 1
            layers.setdefault(layer_idx, []).append(node)

        sorted_layer_keys = sorted(layers.keys())
        total_layers = len(sorted_layer_keys)

        # Coordinate frame bounds in standard Manim 16:9 canvas
        x_min, x_max = -5.0, 5.0
        x_spacing = (x_max - x_min) / max(1, total_layers - 1) if total_layers > 1 else 0.0

        positions: Dict[str, Tuple[float, float, float]] = {}
        for l_idx, key in enumerate(sorted_layer_keys):
            nodes_in_layer = layers[key]
            x_coord = x_min + (l_idx * x_spacing) if total_layers > 1 else 0.0
            count = len(nodes_in_layer)

            # Stagger vertical coordinates around y=0
            y_span = min(5.0, max(2.5, count * 1.8))
            y_spacing = y_span / max(1, count - 1) if count > 1 else 0.0
            y_start = (y_span / 2.0) if count > 1 else 0.0

            for n_idx, node in enumerate(nodes_in_layer):
                if node.position:
                    positions[node.id] = (node.position[0], node.position[1], node.position[2])
                else:
                    y_coord = y_start - (n_idx * y_spacing) if count > 1 else 0.0
                    positions[node.id] = (round(x_coord, 2), round(y_coord, 2), 0.0)

        return positions


