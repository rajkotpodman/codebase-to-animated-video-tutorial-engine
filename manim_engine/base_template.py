        subtitle = Text(subtitle_text, font_size=16, color="{self.theme['subtitle_color']}")
        header = VGroup(title, subtitle).arrange(DOWN, aligned_edge=LEFT, buff=0.15)
        header.to_corner(UL, buff=0.6)

