def generate_scene_script(
    input_data: Union[str, Path, Dict[str, Any], ArchitectureDiagramData],
    output_script_path: Optional[Union[str, Path]] = None,
) -> Tuple[str, Optional[Path]]:
    """Parse JSON or dataclass data, produce Manim Community Python code."""
    if isinstance(input_data, (str, Path)) and (str(input_data).endswith(".py") or "class " in str(input_data)):
        code = str(input_data) if "class " in str(input_data) else Path(input_data).read_text(encoding="utf-8")
        diagram = None
    elif isinstance(input_data, ArchitectureDiagramData):
        diagram = input_data
    elif isinstance(input_data, dict):
        diagram = ArchitectureDiagramData.model_validate(input_data)
    elif isinstance(input_data, (str, Path)) and os.path.exists(str(input_data)):
        raw_text = Path(input_data).read_text(encoding="utf-8")
        parsed_json = json.loads(raw_text)
        diagram = ArchitectureDiagramData.model_validate(parsed_json)
    elif isinstance(input_data, str):
        parsed_json = json.loads(input_data)
        diagram = ArchitectureDiagramData.model_validate(parsed_json)
    else:
        raise ValueError(f"Unsupported input_data type: {type(input_data)}")

    if diagram is not None:
        generator = ArchitectureSceneGenerator(diagram)
        code = generator.generate_code()

    written_path = None
    if output_script_path:
        out_p = Path(output_script_path).resolve()
        out_p.parent.mkdir(parents=True, exist_ok=True)
        out_p.write_text(code, encoding="utf-8")
        written_path = out_p

    return code, written_path


def render_architecture_scene(
    input_data: Union[str, Path, Dict[str, Any], ArchitectureDiagramData],
    output_dir: Optional[Union[str, Path]] = None,
    quality: Literal["l", "m", "h", "k"] = "h",
    fps: int = 30,
    preview: bool = False,
    target_duration: Optional[float] = None,
) -> Path:
    """Dynamically render the Manim script or architecture payload to high-res MP4."""
    service = ManimRenderService()
    return service.render(
        input_data=input_data,
        output_dir=output_dir,
        quality=quality,
        fps=fps,
        preview=preview,
        target_duration=target_duration,
    )


