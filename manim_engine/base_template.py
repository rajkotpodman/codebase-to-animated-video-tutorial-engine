def scale_manim_script_duration(script_code: str, target_duration: float) -> str:
    """Dynamically adjust wait durations in a Manim script to match target audio duration.

    Prevents premature cutoffs and eliminates black screens by extending holds on content.
    """
    if not script_code or target_duration <= 5.0:
        return script_code

    # Strip any trailing FadeOut to black if present to guarantee visual hold
    sanitized = re.sub(
        r"self\.play\(\s*FadeOut\([^)]+\)[^)]*\)\s*\n\s*self\.wait\([^)]*\)",
        "# Ending FadeOut removed to prevent black screen",
        script_code,
    )

    # Estimate current wait and runtime duration
    waits = [float(w) for w in re.findall(r"self\.wait\(\s*([0-9]+(?:\.[0-9]+)?)\s*\)", sanitized)]
    run_times = [float(r) for r in re.findall(r"run_time\s*=\s*([0-9]+(?:\.[0-9]+)?)", sanitized)]
    est_dur = sum(waits) + sum(run_times)

    diff = target_duration - est_dur

    if diff > 0.8:
        # Audio is longer than the animation: extend wait times
        last_wait_match = None
        for m in re.finditer(r"self\.wait\(\s*([0-9]+(?:\.[0-9]+)?)\s*\)", sanitized):
            last_wait_match = m

        if last_wait_match:
            old_val = float(last_wait_match.group(1))
            new_val = round(old_val + diff, 2)
            start, end = last_wait_match.span()
            sanitized = sanitized[:start] + f"self.wait({new_val})" + sanitized[end:]
        else:
            sanitized += f"\n        self.wait({round(diff, 2)})\n"
    elif diff < -5.0 and est_dur > 15.0:
        # Video is significantly longer than audio: scale down wait times smoothly
        scale = max(0.5, target_duration / est_dur)
        sanitized = re.sub(
            r"self\.wait\(\s*([0-9]+(?:\.[0-9]+)?)\s*\)",
            lambda m: f"self.wait({max(1.0, round(float(m.group(1)) * scale, 2))})",
            sanitized,
        )

    return sanitized


def scale_architecture_diagram_duration(
    diagram: ArchitectureDiagramData, target_duration: float
) -> ArchitectureDiagramData:
    """Scale ArchitectureDiagramData config to match target audio duration."""
    if target_duration <= 5.0:
        return diagram

    conn_count = len([c for c in diagram.connections if c.animated])
    flow_dur = diagram.config.duration_per_flow
    base_anim = diagram.config.intro_duration + 0.5 + 2.2 + 0.8 + 2.0 + 1.0 + (conn_count * (flow_dur + 0.4))
    remaining = target_duration - base_anim

    if remaining > 2.0:
        diagram.config.outro_duration = round(remaining, 2)
    elif remaining < 0 and conn_count > 0:
        diagram.config.duration_per_flow = max(1.2, round((target_duration - 8.0) / max(1, conn_count), 2))
        diagram.config.outro_duration = 3.0

    return diagram


