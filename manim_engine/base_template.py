def main() -> None:
    """CLI runner to generate and render Manim architecture scenes."""
    parser = argparse.ArgumentParser(description="Manim Architecture Flow Scene Generator")
    parser.add_argument("--input", "-i", type=str, required=True, help="Path to architecture JSON or Python script")
    parser.add_argument("--output", "-o", type=str, default=None, help="Output Python script path")
    parser.add_argument("--render", "-r", action="store_true", help="Compile and render scene to MP4")
    parser.add_argument("--quality", "-q", choices=["l", "m", "h", "k"], default="h", help="Render video quality")
    parser.add_argument("--fps", type=int, default=30, help="Framerate for rendering (default 30)")
    parser.add_argument("--media-dir", type=str, default="output_videos", help="Directory to save rendered MP4s")

    args = parser.parse_args()

    code, script_path = generate_scene_script(args.input, args.output or "generated_architecture_scene.py")
    print(f"[+] Manim Scene script generated successfully at: {script_path}")

    if args.render:
        print(f"[*] Rendering scene with quality -q{args.quality} at {args.fps} FPS...")
        mp4_path = render_architecture_scene(args.input, output_dir=args.media_dir, quality=args.quality, fps=args.fps)
        print(f"[✔] Video rendered successfully at: {mp4_path}")


if __name__ == "__main__":
    main()
