    def _generate_nodes_data(self) -> str:
        positions = LayeredLayoutEngine.compute_positions(self.data.nodes)
        nodes_dict = {}
        for node in self.data.nodes:
            style = NODE_TYPE_STYLES.get(node.kind, NODE_TYPE_STYLES[NodeType.BACKEND])
            primary_col = node.color or style["primary_color"]
            nodes_dict[node.id] = {
                "id": node.id,
                "label": node.label,
                "kind": node.kind.value,
                "tech": node.tech or style["icon_symbol"],
                "position": list(positions.get(node.id, (0.0, 0.0, 0.0))),
                "color": primary_col,
                "badge": node.badge,
                "details": node.details or [],
            }
        return pprint.pformat(nodes_dict, indent=8)

    def _generate_connections_data(self) -> str:
        conn_list = []
        for c in self.data.connections:
            conn_list.append(
                {
                    "source_id": c.source_id,
                    "target_id": c.target_id,
                    "label": c.label,
                    "protocol": c.protocol,
                    "bidirectional": c.bidirectional,
                    "animated": c.animated,
                    "curvature": c.curvature,
                    "color": c.color,
                    "packet_color": c.packet_color,
                    "packet_speed": c.packet_speed,
                }
            )
        return pprint.pformat(conn_list, indent=8)


