# Manim Code Sanitizer & Auto-Corrector Heuristic
# -----------------------------------------------------------------------------


class ManimCodeSanitizer:
    """Validates Python syntax and auto-corrects AI-generated Manim scripts."""

    @classmethod
    def clean_markdown_fences(cls, code: str) -> str:
        """Strip enclosing markdown code blocks (```python ... ```)."""
        clean = code.strip()
        clean = re.sub(r"^```(?:python)?\s*", "", clean)
        clean = re.sub(r"\s*```$", "", clean)
        return clean.strip()

    @classmethod
    def auto_correct_script(cls, code: str) -> Tuple[bool, str, Optional[str]]:
        """Attempt to validate and auto-correct common AI syntax and Manim issues.

        Returns:
            Tuple of (is_valid, corrected_code, error_message_or_None)
        """
        corrected = cls.clean_markdown_fences(code)

        # 1. Ensure essential Manim imports
        if "from manim import *" not in corrected and "import manim" not in corrected:
            corrected = "from manim import *\n\n" + corrected

        # 2. Replace deprecated / obsolete methods
        deprecated_maps = {
            r"\bShowCreation\b": "Create",
            r"\bFadeInFrom\(([^,]+),\s*[^)]+\)": r"FadeIn(\1)",
            r"\bFadeOutAndShift\(([^,]+),\s*[^)]+\)": r"FadeOut(\1)",
            r"\bGrowFromCenter\b": "Create",
            r"\bApplyWave\b": "Indicate",
        }
        for pattern, repl in deprecated_maps.items():
            corrected = re.sub(pattern, repl, corrected)

        # 3. Fix common LaTeX unescaped backslashes inside Text() calls
        corrected = re.sub(r'Text\("([^"\\]*\\(?:[^\s"\\]+)[^"]*)"\)', r'Text(r"\1")', corrected)

        # 4. AST validation
        try:
            ast.parse(corrected)
            return True, corrected, None
        except SyntaxError as syntax_err:
            logger.warning("Manim script syntax validation failed: %s", syntax_err)
            return False, corrected, str(syntax_err)

    @classmethod
    def detect_scene_classes(cls, code: str) -> List[str]:
        """Inspect Python AST to extract all Scene class names in declaration order."""
        scenes: List[str] = []
        try:
            tree = ast.parse(code)
            for node in ast.walk(tree):
                if isinstance(node, ast.ClassDef):
                    # Check if inherits from Scene or class name ends with 'Scene'
                    is_scene = any(
                        (isinstance(b, ast.Name) and "Scene" in b.id)
                        or (isinstance(b, ast.Attribute) and "Scene" in b.attr)
                        for b in node.bases
                    ) or node.name.endswith("Scene")
                    if is_scene and node.name not in scenes:
                        scenes.append(node.name)
        except Exception as exc:
            logger.debug("AST parsing for scene detection encountered: %s", exc)
            # Regex fallback
            matches = re.findall(r"class\s+([A-Za-z0-9_]+Scene)\s*\(", code)
            scenes = list(dict.fromkeys(matches))

        return scenes


